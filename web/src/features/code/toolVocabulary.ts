/**
 * 一个工具的风险，说给正在被问的那个人听。
 *
 * `risk` 从审批存在的那天起就在线上（`api/types.ts`），而这个控制台只拿它做过一件
 * 事：决定要不要**去掉**「本次会话都允许」那颗按钮。于是读者被要求批准一次工具调用
 * 时，没有任何地方说得出那是哪一类调用；而第三颗按钮不见了的时候，也没有解释为什么
 * 上次有、这次没有。那不叫「只靠颜色传达」，那是根本没有传达。
 *
 * 没学过的值原样落地，不落成沉默：一个这个控制台还不认识的风险，仍然是读者应该看见
 * 的事实。
 *
 * 两处在读它：待批准那张卡（一次已经提议了的调用），以及输入框菜单里的工具清单
 * （下一轮**可能**发生的调用，ADR-096）。同一个词表，因为它们说的是同一件事——把它
 * 抄成两份，第二份会在有人加一档风险的那天开始和第一份不一样。
 */
export const RISK_LABELS: Readonly<Record<string, string>> = {
  read: "只读取",
  write: "会写入",
  external: "会连到外部",
  destructive: "不可撤销",
};

/**
 * 一次批准之后不该被复用的那几档：第二次发生和第一次一样值得问。
 *
 * 只剩 `external`。`destructive` 在这里待到 2026-09-13（ADR-0116）：服务端的
 * 长期规则本来就按参数摘要记，所以「本会话都允许」给一条命令的，只是**这一条**
 * 命令——改一处、跑一次 `pytest`、再改一处、再跑一次，这正是 Claude Code 审批框上
 * 那颗「不再问这条」按钮的用处，也是有人一晚上点了十次同一张卡之后该有的答案。
 */
export const UNREPEATABLE = new Set(["external"]);
